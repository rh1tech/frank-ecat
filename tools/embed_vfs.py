#!/usr/bin/env python3
#
# frank-ecat — pack the eCat3 files of one firmware into a read-only flash VFS
#
# Copyright (c) 2026 Mikhail Matveev <xtreme@rh1.tech>
# SPDX-License-Identifier: GPL-3.0-or-later
#
# Usage: embed_vfs.py --deploy ecat3/deploy --headless build-host/eCat3-headless
#                     --out-dir DIR  MACHINE...
# MACHINE: a configuration relative to deploy/computers (Radio-86rk.cfg or an
# extension, Spektr001.ext, which is flattened with eCat3-headless
# --print-config: the firmware has no extension engine).
#
# Packed, under /ecat/ (the paths the firmware hands the emulator):
#   computers/<dir>/<name>.cfg   every machine, flat
#   computers/<dir>/files/*      the files of each machine directory
#   computers/<dir>/*.kbd|keys|map|remap|chr
#   data/*.kbd|keys|map|remap|chr|ini   the shared keyboard and charset data
#   ecat.ini                     deploy/.ecat.ini, the shipped defaults
# Output: vfs_data.S (the file bodies, .incbin) and vfs_table.c (the index),
# and machines.txt (the configurations, in order, for the machine menu).

import argparse
import os
import subprocess
import sys

DATA_EXT = ('.kbd', '.keys', '.map', '.remap', '.chr', '.ini')
SKIP_EXT = ('.md', '.svg', '.txt', '.png', '.xls', '.dis', '.css')


def c_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--deploy', required=True)
    ap.add_argument('--headless', required=True)
    ap.add_argument('--out-dir', required=True)
    ap.add_argument('machines', nargs='+')
    a = ap.parse_args()
    a.headless = os.path.abspath(a.headless)

    deploy = os.path.abspath(a.deploy)
    comp = os.path.join(deploy, 'computers')
    out = os.path.abspath(a.out_dir)
    flat_dir = os.path.join(out, 'flat')
    os.makedirs(flat_dir, exist_ok=True)

    entries = []    # (vfs path, source file)
    seen = set()

    def add(vpath, src):
        if vpath in seen:
            return
        seen.add(vpath)
        entries.append((vpath, src))

    machines = []
    dirs = []
    for m in a.machines:
        src = os.path.join(comp, m)
        if not os.path.isfile(src):
            sys.exit('embed_vfs: no such machine file: ' + src)
        d = os.path.dirname(m)
        base = os.path.splitext(os.path.basename(m))[0]
        vcfg = '/ecat/computers/%s/%s.cfg' % (d, base)
        if m.endswith('.ext'):
            r = subprocess.run([a.headless, '--workdir', deploy, '--print-config', m],
                               cwd=comp, capture_output=True)
            if r.returncode != 0 or not r.stdout:
                sys.exit('embed_vfs: --print-config %s failed: %s' % (m, r.stderr.decode(errors='replace')))
            flat = os.path.join(flat_dir, d.replace('/', '_') + '_' + base + '.cfg')
            with open(flat, 'wb') as f:
                f.write(r.stdout)
            add(vcfg, flat)
        else:
            add(vcfg, src)
        machines.append(vcfg)
        if d not in dirs:
            dirs.append(d)

    for d in dirs:
        full = os.path.join(comp, d)
        for name in sorted(os.listdir(full)):
            p = os.path.join(full, name)
            if os.path.isfile(p) and name.lower().endswith(DATA_EXT):
                add('/ecat/computers/%s/%s' % (d, name), p)
        files = os.path.join(full, 'files')
        if os.path.isdir(files):
            for name in sorted(os.listdir(files)):
                p = os.path.join(files, name)
                if os.path.isfile(p) and not name.lower().endswith(SKIP_EXT):
                    add('/ecat/computers/%s/files/%s' % (d, name), p)

    data = os.path.join(deploy, 'data')
    for name in sorted(os.listdir(data)):
        p = os.path.join(data, name)
        if os.path.isfile(p) and name.lower().endswith(DATA_EXT):
            add('/ecat/data/' + name, p)
    add('/ecat/ecat.ini', os.path.join(deploy, '.ecat.ini'))

    with open(os.path.join(out, 'vfs_data.S'), 'w') as f:
        f.write('/* generated by tools/embed_vfs.py */\n')
        f.write('    .section .rodata.ecat_vfs, "a"\n')
        for i, (v, src) in enumerate(entries):
            f.write('    .balign 4\n    .global ecat_vfs_f%d\necat_vfs_f%d:\n' % (i, i))
            f.write('    .incbin %s\n' % c_str(src))
        f.write('    .balign 4\n')

    total = 0
    with open(os.path.join(out, 'vfs_table.c'), 'w') as f:
        f.write('/* generated by tools/embed_vfs.py */\n#include "frank_vfs.h"\n\n')
        for i, _ in enumerate(entries):
            f.write('extern const uint8_t ecat_vfs_f%d[];\n' % i)
        f.write('\nconst ecat_vfs_entry_t ecat_vfs[] = {\n')
        for i, (v, src) in enumerate(entries):
            size = os.path.getsize(src)
            total += size
            f.write('    { %s, ecat_vfs_f%d, %du },\n' % (c_str(v), i, size))
        f.write('};\nconst unsigned ecat_vfs_count = %d;\n\n' % len(entries))
        f.write('const char *const ecat_machines[] = {\n')
        for m in machines:
            f.write('    %s,\n' % c_str(m))
        f.write('};\nconst unsigned ecat_machine_count = %d;\n' % len(machines))

    with open(os.path.join(out, 'machines.txt'), 'w') as f:
        f.write('\n'.join(machines) + '\n')
    print('embed_vfs: %d files, %d KB, %d machines' % (len(entries), total // 1024, len(machines)))


if __name__ == '__main__':
    main()
