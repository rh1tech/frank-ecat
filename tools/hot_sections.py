# Usage: hot_sections.py [--family F] LIST OUT.ld NM OBJECT...
# LIST: demangled names (platform/hot_functions.txt), or a prefix and '*'. OUT.ld gets one input
# section line per matching function (-ffunction-sections: .text.<mangled>),
# included by memmap_ecat.ld inside its .ram_hot output section. A line
# "@ family ..." scopes the names after it ("@ all": every firmware); with
# --family only the names scoped to that family (or all) are taken.

import subprocess
import sys


def main():
    args = sys.argv[1:]
    family = None
    if args and args[0] == '--family':
        family = args[1]
        args = args[2:]
    lst, out, nm = args[0], args[1], args[2]
    objs = args[3:]
    wanted = []
    scope = ['all']
    for line in open(lst, encoding='utf-8'):
        line = line.split('#', 1)[0].strip()
        if not line:
            continue
        if line.startswith('@'):
            scope = line[1:].split()
            continue
        if family is None or 'all' in scope or family in scope:
            if line not in wanted:
                wanted.append(line)
    found = {}
    for o in objs:
        r = subprocess.run([nm, '--defined-only', o], capture_output=True, text=True)
        mangled = [l.split()[-1] for l in r.stdout.splitlines() if len(l.split()) == 3 and l.split()[1] in 'TtWw']
        if not mangled:
            continue
        d = subprocess.run([nm.replace('nm', 'c++filt')], input='\n'.join(mangled),
                           capture_output=True, text=True).stdout.splitlines()
        for m, dm in zip(mangled, d):
            base = dm.split('(', 1)[0]
            for w in wanted:
                # "Class::_*": every name with that prefix
                if base == w or (w.endswith('*') and base.startswith(w[:-1])):
                    found.setdefault(w, set()).add(m)
    with open(out, 'w') as f:
        f.write('/* generated by tools/hot_sections.py from %s */\n' % lst)
        for w in wanted:
            for m in sorted(found.get(w, ())):
                f.write('        *(.text.%s .text.%s.*)\n' % (m, m))
    missing = [w for w in wanted if w not in found]
    n = sum(len(v) for v in found.values())
    print('hot_sections: %d functions (%d symbols)%s' % (len(found), n,
          ('; not found: ' + ', '.join(missing)) if missing else ''))


if __name__ == '__main__':
    main()
