# Usage: hot_sections.py LIST OUT.ld NM OBJECT...
# LIST: demangled names (platform/hot_functions.txt). OUT.ld gets one input
# section line per matching function (-ffunction-sections: .text.<mangled>),
# included by memmap_ecat.ld inside its .ram_hot output section.

import subprocess
import sys


def main():
    lst, out, nm = sys.argv[1], sys.argv[2], sys.argv[3]
    objs = sys.argv[4:]
    wanted = []
    for line in open(lst, encoding='utf-8'):
        line = line.split('#', 1)[0].strip()
        if line:
            wanted.append(line)
    found = {}
    for o in objs:
        r = subprocess.run([nm, '--defined-only', o], capture_output=True, text=True)
        mangled = [l.split()[-1] for l in r.stdout.splitlines() if len(l.split()) == 3 and l.split()[1] in 'TtWw']
        if not mangled:
            continue
        d = subprocess.run([nm.replace('nm', 'c++filt')], input='\n'.join(mangled),
                           capture_output=True, text=True).stdout.splitlines()
        for m, dm in zip(mangled, d):
            base = dm.split('(', 1)[0]
            for w in wanted:
                if base == w:
                    found.setdefault(w, set()).add(m)
    with open(out, 'w') as f:
        f.write('/* generated by tools/hot_sections.py from %s */\n' % lst)
        for w in wanted:
            for m in sorted(found.get(w, ())):
                f.write('        *(.text.%s .text.%s.*)\n' % (m, m))
    missing = [w for w in wanted if w not in found]
    n = sum(len(v) for v in found.values())
    print('hot_sections: %d functions (%d symbols)%s' % (len(found), n,
          ('; not found: ' + ', '.join(missing)) if missing else ''))


if __name__ == '__main__':
    main()
